"""Generate Python-3.12-compatible Unicode predicate tables for spacy-rs."""
import sys, unicodedata
preds = {
    "ALPHA": lambda c: c.isalpha(),
    "DIGIT": lambda c: c.isdigit(),
    "SPACE": lambda c: c.isspace(),
    "UPPER": lambda c: c.istitle() and unicodedata.category(c) != "Lt",
    "LOWER": lambda c: c.islower(),
    "TITLE": lambda c: unicodedata.category(c) == "Lt",
    "PUNCT": lambda c: unicodedata.category(c).startswith("P"),
    "CURRENCY": lambda c: unicodedata.category(c) == "Sc",
    "WORD": lambda c: c.isalnum() or c == "_",
    "CASE_IGNORABLE": lambda c: unicodedata.category(c) in ("Mn", "Me", "Cf", "Lm", "Sk")
    or c in "\u0027\u002E\u003A\u00B7\u0387\u05F4\u2018\u2019\u2024\uFE13\uFE52\uFE55\uFF07\uFF0E\uFF1A",
}
out = ["// @generated by tools/gen_unicode.py from Python %s (Unicode %s). Do not edit.\n" % (sys.version.split()[0], unicodedata.unidata_version)]
for name, f in preds.items():
    ranges = []
    start = None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            v = False
        else:
            v = f(chr(cp))
        if v and start is None: start = cp
        if not v and start is not None:
            ranges.append((start, cp - 1)); start = None
    if start is not None: ranges.append((start, 0x10FFFF))
    out.append("pub(crate) static %s: &[(u32, u32)] = &[\n" % name)
    line = ""
    for a, b in ranges:
        item = "(0x%X, 0x%X)," % (a, b)
        if len(line) + len(item) > 95:
            out.append("    " + line.rstrip() + "\n"); line = ""
        line += item + " "
    if line: out.append("    " + line.rstrip() + "\n")
    out.append("];\n\n")
# Characters where str.lower() is not a 1:1 mapping or differs; export full lower table as diffs
low = []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF: continue
    c = chr(cp); l = c.lower()
    if l != c: low.append((cp, l))
out.append("/// Python `str.lower()` for single characters (only characters that change).\n")
out.append("pub(crate) static LOWER_MAP: &[(u32, &str)] = &[\n")
for cp, l in low:
    out.append("    (0x%X, \"%s\"),\n" % (cp, "".join("\\u{%X}" % ord(x) for x in l)))
out.append("];\n")
open(sys.argv[1], "w").write("".join(out))
